/**
 * The monthly SEO report job.
 *
 *   1. report   — a `reports` row for the month, generated by the same
 *                 `runReportJob` as an on-demand report, so the email shows the
 *                 same ReportFindings and grounded narrative as the Reports tab.
 *   2. pdf      — if a worker with Chromium is online, ask it to print the
 *                 report and wait for it (briefly inline, then across ticks,
 *                 never beyond the render's own expiry). No worker, a failed
 *                 render or a timeout: the email goes without the attachment
 *                 and with a sign-in link to download the PDF instead.
 *   3. send     — one tracked email per recipient, keyed per dealership, month
 *                 and address, so a retry (or a re-run after the period is
 *                 released) never sends anyone the same month twice.
 *
 * Progress is kept in the job's payload, so a retry resumes rather than
 * regenerating. No render key is ever placed in an email: the key lives only in
 * the `report_pdf` job's payload, and the email links to the signed-in page.
 */

/** Long enough for a warm worker to print a report, short enough not to hog a tick slot. */
const INLINE_PDF_WAIT_MS = 90_000;
const PDF_POLL_MS = 3_000;
/** Leave the rest of the tick for sending. */
const SEND_RESERVE_MS = 40_000;
/** A report narrative may call the model; the same budget the runner gives a `report` job. */
const REPORT_BUDGET_MS = 150_000;

export interface MonthlyJobPayload {
  dealershipId: number;
  month: string;
  manual?: boolean;
  requestedBy?: number | null;
  /** Manual test send to one address instead of the dealership's recipients. */
  onlyTo?: string | null;
  nonce?: string;
  reportId?: number;
  renderId?: number;
  renderRequestedAt?: number;
  pdf?: "attach" | "none";
}

export type MonthlyStep = { done: true; result: Record<string, unknown> } | { done: false; deferMs: number };

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function savePayload(jobId: number, payload: MonthlyJobPayload) {
  await db.update(jobs).set({ payload: payload as unknown as Record<string, unknown> }).where(eq(jobs.id, jobId));
}

/** A crawler worker (which carries Chromium) reported recently, in any region. */
async function pdfRendererOnline(): Promise<boolean> {
  const rows = await db.execute<{ one: number }>(sql`
    select 1 as one from crawler_workers
    where kind in ('worker', 'cli') and last_seen_at > now() - interval '3 minutes'
    limit 1
  `);
  return (rows as unknown as unknown[]).length > 0;
}

const toLine = (c: CheckChange): MonthlyChangeLine => ({ title: c.title, priority: c.priority, before: c.before, after: c.after });

export async function runMonthlyReportJob(job: Job, deadline: number): Promise<MonthlyStep> {
  const payload = { ...(job.payload as unknown as MonthlyJobPayload) };
  const dealer = await getDealershipForReport(Number(payload.dealershipId));
  if (!dealer) return { done: true, result: { skipped: "dealership no longer exists" } };
  if (!payload.manual && (!dealer.isActive || !dealer.seoEnabled)) return { done: true, result: { skipped: "dealership inactive or SEO monitoring off" } };

  // ── 1. The report ──────────────────────────────────────────────────
  if (!payload.reportId) {
    payload.reportId = await db.transaction(async (tx) => {
      const [row] = await tx.insert(reports).values({ dealershipId: dealer.id, requestedBy: payload.requestedBy ?? null, status: "queued", periodMonth: payload.month }).returning({ id: reports.id });
      await tx.update(jobs).set({ payload: { ...payload, reportId: row.id } as unknown as Record<string, unknown> }).where(eq(jobs.id, job.id));
      return row.id;
    });
  }
  let [report] = await db.select().from(reports).where(eq(reports.id, payload.reportId)).limit(1);
  if (!report) return { done: true, result: { skipped: "report row missing" } };
  if (report.status !== "completed" && report.status !== "failed") {
    if (aiReportsConfigured() && deadline - Date.now() < REPORT_BUDGET_MS) return { done: false, deferMs: 0 };
    await runReportJob(report.id); // throws only for transient model errors → job retry
    [report] = await db.select().from(reports).where(eq(reports.id, payload.reportId)).limit(1);
  }
  if (!report || report.status !== "completed" || !report.findings || !report.narrative) {
    await logger.warn("reports", "Monthly report not sent: the report could not be built", { month: payload.month, error: report?.error ?? null }, dealer.id);
    return { done: true, result: { skipped: report?.error ?? "report not completed", reportId: payload.reportId } };
  }
  const findings = report.findings as ReportFindings;
  const narrative = report.narrative as ReportNarrative;

  // ── 2. The PDF ─────────────────────────────────────────────────────
  if (!payload.pdf) {
    if (!payload.renderId) {
      if (await pdfRendererOnline().catch(() => false)) {
        const status = await requestReportPdf(dealer.id, payload.requestedBy ?? null, { reuseInFlight: false });
        if (status.state === "failed" || status.id === 0) payload.pdf = "none";
        else {
          payload.renderId = status.id;
          payload.renderRequestedAt = Date.now();
        }
      } else {
        payload.pdf = "none";
      }
      await savePayload(job.id, payload);
    }
    if (!payload.pdf && payload.renderId) {
      const waitUntil = Math.min(Date.now() + INLINE_PDF_WAIT_MS, deadline - SEND_RESERVE_MS);
      for (;;) {
        const s = await getRenderStatus(payload.renderId, dealer.id);
        if (!s || s.state === "failed") payload.pdf = "none";
        else if (s.state === "ready") payload.pdf = "attach";
        if (payload.pdf || Date.now() + PDF_POLL_MS > waitUntil) break;
        await sleep(PDF_POLL_MS);
      }
      if (!payload.pdf) {
        // The render key dies after RENDER_TOKEN_TTL_MS; waiting longer cannot help.
        if (Date.now() - (payload.renderRequestedAt ?? 0) > RENDER_TOKEN_TTL_MS + 60_000) payload.pdf = "none";
        else {
          await savePayload(job.id, payload);
          return { done: false, deferMs: 20_000 };
        }
      }
      await savePayload(job.id, payload);
    }
  }

  // ── 3. Send ────────────────────────────────────────────────────────
  const settings = await getSettings();
  const recipients = payload.onlyTo ? [payload.onlyTo.toLowerCase()] : [...new Set([...(dealer.notificationEmails ?? []), ...settings.managementRecipients].map((e) => e.toLowerCase()))];
  const label = monthLabel(payload.month);
  if (recipients.length === 0) {
    await recordSkippedNoRecipients({
      dedupeKey: `monthly:${dealer.id}:${payload.month}:no-recipients`,
      kind: "monthly_report",
      dealershipId: dealer.id,
      subject: `Monthly SEO report — ${label}: ${dealer.name}`,
      reason: `No active email recipients configured for ${dealer.name}. Add notification emails to this dealership, or management recipients in Settings.`,
      payload: { reportId: report.id, month: payload.month },
    });
    if (payload.renderId) await discardRender(payload.renderId, dealer.id);
    return { done: true, result: { recipients: 0, reportId: report.id } };
  }

  const pdf = payload.pdf === "attach" && payload.renderId ? await peekRenderedPdf(payload.renderId, dealer.id) : null;
  const [scanRow] = await db.select({ detailsRetained: seoScans.detailsRetained }).from(seoScans).where(eq(seoScans.id, findings.scan.id)).limit(1);
  const previous = await getSnapshotBefore(dealer.id, payload.month);
  const cmp = previous
    ? compareMonths({ month: payload.month, score: findings.scan.score, checks: findings.issues.map((i) => ({ checkKey: i.checkKey, priority: i.priority, affectedPages: i.affectedPages })) }, { month: previous.month, score: previous.score, checks: previous.checks })
    : null;
  const base = env().APP_URL.replace(/\/$/, "");
  const branding = resolveBranding(dealer);
  // "What to do next" leaves out checks whose every finding A3 marked ignored
  // (issue workflow); the counts and score above still include them.
  const allIgnored = new Set((await getOpportunities(findings.scan.id, { includeIgnored: true })).filter((o) => !isActionable(o, o.ignoredFindings ?? 0)).map((o) => o.checkKey));
  const actions = narrative.recommendedActions.filter((a) => !allIgnored.has(a.checkKey));
  const email = renderMonthlyReportEmail({
    dealershipName: dealer.name,
    websiteUrl: dealer.websiteUrl,
    monthLabel: label,
    score: findings.scan.score,
    statusLabel: findings.scan.outcomeLabel,
    pagesAnalyzed: findings.scan.pagesAnalyzed,
    pagesProtected: findings.scan.pagesProtected,
    counts: { critical: findings.counts.critical, high: findings.counts.high, medium: findings.counts.medium, low: findings.counts.low },
    executiveSummary: narrative.executiveSummary,
    actions: actions.map((a) => ({ priority: a.priority, title: a.title, action: a.action })),
    comparison:
      previous && cmp
        ? {
            previousMonthLabel: monthLabel(previous.month),
            gap: previous.month !== previousMonth(payload.month),
            previousScore: previous.score,
            scoreDelta: cmp.scoreDelta,
            newIssues: cmp.newChecks.map(toLine),
            resolvedIssues: cmp.resolvedChecks.map(toLine),
            improved: cmp.improved.map(toLine),
            worsened: cmp.worsened.map(toLine),
          }
        : null,
    detailsRetained: scanRow?.detailsRetained ?? true,
    pdf: pdf ? "attached" : "download",
    reportUrl: `${base}/report/${dealer.id}`,
    dashboardUrl: `${base}/dealerships/${dealer.id}?tab=reports&report=${report.id}`,
    branding: { ...branding, logoAlt: dealer.name },
    test: Boolean(payload.manual),
  });

  const out = { recipients: recipients.length, sent: 0, skipped: 0, failed: 0, reportId: report.id, pdfAttached: Boolean(pdf) };
  for (const to of recipients) {
    const r = await sendTrackedEmail({
      dedupeKey: monthlyEmailDedupeKey(payload, to),
      kind: "monthly_report",
      dealershipId: dealer.id,
      to,
      subject: email.subject,
      html: email.html,
      text: email.text,
      payload: { reportId: report.id, month: payload.month, pdfAttached: Boolean(pdf), manual: Boolean(payload.manual) },
      attachments: pdf ? [{ filename: pdf.filename, content: pdf.pdf, contentType: "application/pdf" }] : undefined,
    });
    out[r]++;
  }
  // Failed recipients are retried by the job (the PDF row is kept for them); everyone served is skipped.
  if (out.failed > 0) throw new Error(`${out.failed} monthly report email(s) failed to send; they will be retried.`);
  if (payload.renderId) await discardRender(payload.renderId, dealer.id).catch((err) => logger.warn("reports", "Could not discard a delivered render", { error: errorMessage(err) }, dealer.id));
  await logger.info("reports", "Monthly report sent", { month: payload.month, ...out }, dealer.id);
  return { done: true, result: out };
}
